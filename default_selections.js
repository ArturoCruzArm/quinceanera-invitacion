// Initialize selections from defaults
function initializeDefaultSelections() {
    const storageKey = 'maria_esther_xv_photo_selections';
    const stored = localStorage.getItem(storageKey);
    
    if (!stored) {
        localStorage.setItem(storageKey, JSON.stringify(defaultSelections));
        console.log(`Loaded ${Object.keys(defaultSelections).length} default classifications`);
    }
}

// Auto-initialize when script loads
if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initializeDefaultSelections);
    } else {
        initializeDefaultSelections();
    }
}

