// Initialize selections from defaults
function initializeDefaultSelectionsJPG() {
    const storageKey = 'xv_maria_esther_jpg_selections';
    const stored = localStorage.getItem(storageKey);
    
    if (!stored) {
        // Pre-load default classifications
        const selectionsToStore = {};
        Object.entries(DEFAULT_SELECTIONS_JPG).forEach(([filename, data]) => {
            selectionsToStore[filename] = {
                categories: data.categories,
                notes: data.notes
            };
        });
        
        localStorage.setItem(storageKey, JSON.stringify(selectionsToStore));
        console.log(`Loaded ${Object.keys(selectionsToStore).length} default classifications for María Esther JPG`);
    }
}

// Auto-initialize when script loads
if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initializeDefaultSelectionsJPG);
    } else {
        initializeDefaultSelectionsJPG();
    }
}

// Export for use in Node/modules
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { DEFAULT_SELECTIONS_JPG, initializeDefaultSelectionsJPG };
}
